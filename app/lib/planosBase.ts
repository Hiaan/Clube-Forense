// Fica no código pelo mesmo motivo da curadoria e dos aprovados: é o piso. O
// painel continua sendo quem manda — assim que alguém edita o plano de um
// estado, o banco passa a responder por ele e isto aqui não é mais consultado
// para aquela UF.
//
